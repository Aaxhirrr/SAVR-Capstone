export function canonicalBrand(name: string) {
  const clean = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (clean.includes('atlanticsuperstore')) return 'atlanticsuperstore';
  if (clean.includes('superstore')) return 'superstore';
  if (clean.includes('ttsupermarket') || clean.includes('tandt'))
    return 'tandt';
  return knownStores.find((s) => clean.includes(s.brand))?.brand ?? clean;
}
